"""Compiled UI, audio lifecycle and explicit onboarding/mobile fixtures; no model download."""
import os,sys,json,ast
from pathlib import Path
root=Path(__file__).resolve().parent.parent
sys.path.insert(0,str(root/'work'/'python'))
from playwright.sync_api import sync_playwright,expect
os.environ['TEMP']=os.environ['TMP']=str(root/'work'/'temp')
base=sys.argv[1] if len(sys.argv)>1 else 'http://127.0.0.1:4173/'
tree=ast.parse((root/'tests'/'playthrough.py').read_text(encoding='utf-8'))
node=next(n for n in ast.walk(tree) if isinstance(n,ast.FunctionDef) and n.name=='bind_runtime')
exec(compile(ast.Module(body=[node],type_ignores=[]),'bind_runtime','exec'))
errors=[];external=[];checks=[]
with sync_playwright() as p:
    browser=p.chromium.launch(channel='chrome',headless=True,args=['--enable-unsafe-webgpu'])
    page=browser.new_page(viewport={'width':1440,'height':900})
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('request',lambda r:external.append(r.url) if not r.url.startswith((base.split('/?')[0].rstrip('/'),'blob:','data:')) else None)
    page.add_init_script('''(()=>{window.qaAudioContexts=[];const Original=AudioContext;window.AudioContext=class extends Original{constructor(...args){super(...args);this.qaGains=[];qaAudioContexts.push(this);}createGain(){const g=super.createGain();this.qaGains.push(g);return g;}}})()''')
    page.goto(base,wait_until='networkidle');expect(page.get_by_role('button',name='START EXPERIENCE')).to_be_enabled(timeout=30000)
    page.get_by_role('button',name='Behind the System',exact=False).click()
    page.get_by_role('tab',name='Arquitectura',exact=True).focus();page.keyboard.press('End')
    expect(page.get_by_role('tab',name='Decisiones',exact=True)).to_have_attribute('aria-selected','true')
    expect(page.locator('.engineering-decisions')).to_contain_text('2048')
    expect(page.get_by_role('link',name='Portfolio',exact=False)).to_have_attribute('href','https://aleviclop.dev')
    expect(page.get_by_role('link',name='GitHub',exact=False)).to_have_attribute('href','https://github.com/AVL05')
    page.screenshot(path=str(root/'outputs'/'polish-decisions.png'))
    page.get_by_role('button',name='Volver al inicio',exact=True).click()
    page.wait_for_function("document.activeElement.matches('[data-open-system]')")
    checks.append('engineering decisions, verified configurable author links and restored keyboard focus')
    page.get_by_role('button',name='Ajustes y controles').click();page.get_by_label('Control de cámara').select_option('drag');page.get_by_role('button',name='Volver',exact=True).click();page.get_by_role('button',name='START EXPERIENCE').click()
    bind_runtime()
    page.wait_for_function("qaAudioContexts[0]?.state==='running'")
    page.get_by_label('Silenciar sonido').click();page.wait_for_function('qaAudioContexts[0].qaGains[0].gain.value<0.02')
    page.get_by_label('Activar sonido').click();page.wait_for_function('qaAudioContexts[0].qaGains[0].gain.value>0.3')
    page.evaluate("()=>{const p=qaGame.getState().progress;qaGame.setState({progress:{...p,story:{...p.story,stats:{...p.story.stats,interactions:2}}}})}")
    expect(page.get_by_label('Guía de primeros pasos')).to_be_visible()
    page.evaluate("()=>{const p=qaGame.getState().progress;qaGame.setState({progress:{...p,cell:true}})}")
    expect(page.get_by_label('Guía de primeros pasos')).to_contain_text('02 /')
    page.evaluate("()=>{const p=qaGame.getState().progress;qaGame.setState({progress:{...p,installed:true},phase:'terminal',activeTerminal:'containment'})}")
    expect(page.locator('.ai-invitation')).to_contain_text('300 MB')
    assert page.locator('.command-list').bounding_box()['y']<page.locator('.ai-terminal').bounding_box()['y']
    page.locator('.ai-invitation').click();page.wait_for_function("document.activeElement.id==='echo-local-ai'")
    expect(page.locator('.ai-brief')).to_contain_text('1–1,5 GB')
    expect(page.locator('.ai-brief')).to_contain_text('hasta un minuto')
    page.get_by_label('Tu instrucción').fill('Activa el reactor')
    page.get_by_role('button',name='Enviar',exact=True).click()
    expect(page.get_by_role('button',name='Confirmar acción')).to_be_visible()
    page.get_by_role('button',name='Descartar',exact=True).click()
    expect(page.get_by_role('button',name='Confirmar acción')).to_have_count(0)
    expect(page.locator('.ai-diagnostics pre')).to_contain_text('Propuesta descartada por el jugador')
    assert not page.evaluate('qaGame.getState().progress.power')
    assert not external,external
    page.screenshot(path=str(root/'outputs'/'polish-ai-offer.png'))
    page.get_by_role('button',name='Cerrar enlace').click()
    page.keyboard.press('Escape');page.wait_for_function("qaAudioContexts[0].state==='suspended'")
    page.get_by_role('button',name='Reanudar experiencia').click();page.wait_for_function("qaAudioContexts[0].state==='running'")
    checks.append('onboarding after two interactions, AI consent/requisites, Web Audio mute/pause/resume')
    page.close()
    context=browser.new_context(viewport={'width':390,'height':844},is_mobile=True,has_touch=True,reduced_motion='reduce')
    page=context.new_page();page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(base,wait_until='networkidle');expect(page.get_by_role('button',name='START EXPERIENCE')).to_be_enabled(timeout=30000)
    page.get_by_role('button',name='START EXPERIENCE').tap();bind_runtime()
    message=page.locator('.echo-message').bounding_box();journal=page.locator('.journal-access').bounding_box()
    assert message['y']+message['height']<=journal['y'],(message,journal)
    expect(page.locator('.touch-interact')).to_be_disabled()
    page.evaluate("()=>{qaScene.getState().setFrameloop('never');qaGame.setState({target:'cell'})}")
    expect(page.get_by_label('Guía de primeros pasos')).to_have_count(0)
    expect(page.locator('.touch-interact')).to_be_enabled()
    prompt=page.locator('.interact-prompt').bounding_box();message=page.locator('.echo-message').bounding_box()
    assert prompt['y']+prompt['height']<=message['y'],(prompt,message)
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    page.evaluate("qaGame.setState({phase:'terminal',activeTerminal:'containment'})")
    expect(page.get_by_role('button',name='Autorizar compuerta de salida')).to_be_in_viewport()
    checks.append('390px mobile message/journal/prompt separation and contextual interaction; controlled target fixture')
    context.close();browser.close()
assert not errors,errors
(root/'outputs'/'POLISH-UI.json').write_text(json.dumps({'url':base,'status':'PASS','checks':checks,'errors':errors,'externalBeforeConsent':external,'audioScope':'Web Audio graph/state checks; no claim of listening on physical hardware'},ensure_ascii=False,indent=2),encoding='utf-8')
print('POLISH UI PASS',flush=True)
